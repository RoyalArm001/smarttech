  site.sections.about = function about() {
    var e = site.utils.escapeHtml;
    var company = site.content.company;
    var copy = presentationCopy();
    var paragraphItems = copy.paragraphs || site.i18n.get("about.paragraphs", company.about);
    var heroText = paragraphItems.join(" ");
    if (heroText.length > 300) {
      heroText = heroText.slice(0, 300) + "...";
    }

    var paragraphs = paragraphItems.map(function (text) {
      return '<p>' + e(text) + '</p>';
    }).join("");

    var values = (copy.values || site.i18n.get("about.values", company.values)).map(function (value) {
      return '' +
        '<article class="value-card reveal">' +
          '<h3>' + e(value.title) + '</h3>' +
          '<p>' + e(value.text) + '</p>' +
        '</article>';
    }).join("");

    var stats = (copy.stats || site.i18n.get("stats", company.stats)).map(function (stat) {
      return '' +
        '<div class="about-stat">' +
          '<strong>' + e(stat.value) + '</strong>' +
          '<span>' + e(stat.label) + '</span>' +
        '</div>';
    }).join("");

    var staff = copy.staff.map(function (item) {
      return '' +
        '<div class="about-team-stat reveal">' +
          '<strong>' + e(item.value) + '</strong>' +
          '<span>' + e(item.label) + '</span>' +
        '</div>';
    }).join("");

    var advantages = copy.advantages.map(function (item) {
      return '<li>' + e(item) + '</li>';
    }).join("");

    var licenseDocuments = company.licenseDocuments || [];
    var licenseCards = licenseDocuments.map(function (item) {
      return '' +
        '<a class="about-license-card" href="' + e(item.image) + '" data-license-viewer data-license-title="' + e(item.title) + '">' +
          '<img src="' + e(item.thumb || item.image) + '" alt="' + e(item.alt || item.title) + '" loading="lazy" decoding="async">' +
          '<span>' + e(item.title) + '</span>' +
        '</a>';
    }).join("");

    return '' +
      site.sections.pageHero({
        eyebrow: site.i18n.get("about.eyebrow"),
        eyebrowKey: "about.eyebrow",
        title: site.i18n.get("about.title"),
        titleKey: "about.title",
        text: heroText,
        textKey: "about.paragraphs",
        image: company.heroImages[1],
        tone: "about"
      }) +
      '<section id="about-content" class="section about-section">' +
        '<div class="container about-grid">' +
          '<div class="about-media reveal">' +
            '<img src="' + e(company.heroImages[1]) + '" alt="Smart Tech workspace" loading="lazy">' +
          '</div>' +
          '<div class="about-copy reveal">' +
            paragraphs +
            '<div class="about-proof-grid">' + stats + '</div>' +
          '</div>' +
        '</div>' +
        '<div class="container values-grid">' + values + '</div>' +
        '<div class="container about-info-grid">' +
          '<article class="about-info-panel reveal">' +
            '<h2>' + e(copy.staffTitle) + '</h2>' +
            '<p>' + e(copy.staffText) + '</p>' +
            '<div class="about-team-grid">' + staff + '</div>' +
          '</article>' +
          '<article class="about-info-panel reveal">' +
            '<h2>' + e(copy.advantageTitle) + '</h2>' +
            '<ul>' + advantages + '</ul>' +
          '</article>' +
        '</div>' +
        '<div class="container about-license reveal">' +
          '<h2>' + e(copy.licenseTitle) + '</h2>' +
          '<p>' + e(copy.licenseText) + '</p>' +
          (licenseCards ? '<div class="about-license-grid">' + licenseCards + '</div>' : '') +
        '</div>' +
      '</section>';
  };
