'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'deploy', 'cpanel');
const marker = '.smarttech-package';
const roots = ['src','pages','lib','admin','vendor','sql','scripts','img','content'];
const files = ['package.json','package-lock.json','app.js','new-start.js','server.js','manifest.json','robots.txt','sitemap.xml','llms.txt','CPANEL.md','CPANEL-VALIDATION.md','tools/start-local.js','tools/cpanel-diagnose.js'];
const forbiddenDirectories = new Set(['node_modules','.git','dist','deploy','data','published','admin-album','migration-private']);
const copied = [];
function copy(relative) {
  const source = path.join(root, relative);
  if (!fs.existsSync(source)) throw new Error('Missing package source: ' + relative);
  const stat = fs.lstatSync(source);
  if (stat.isSymbolicLink()) throw new Error('Package symlinks are not allowed: ' + relative);
  if (stat.isDirectory()) {
    if (forbiddenDirectories.has(path.basename(source))) return;
    for (const name of fs.readdirSync(source)) copy(path.join(relative,name));
    return;
  }
  const name = path.basename(source);
  if (name === 'migration.env.example') return; // Superseded MySQL plan, not runtime config.
  if (name.startsWith('.env') || /\.(?:key|dump|partial|log|jsonl|zip)$/i.test(name)) return;
  if (relative.replace(/\\/g,'/').startsWith('database/backups/') && !/\.enc$|^README\.md$/.test(name)) return;
  if (relative.replace(/\\/g,'/').startsWith('database/seed/') && name !== 'README.md') return;
  const bytes = fs.readFileSync(source);
  if (/\.(?:js|cjs|mjs|json|html|md|sql|example)$/i.test(name)) {
    const text = bytes.toString('utf8');
    if (/\bsk-(?:proj-)?[A-Za-z0-9_-]{40,}|\bsb_secret_[A-Za-z0-9_-]{25,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/.test(text)) {
      throw new Error('Credential-like content in ' + relative + '; value withheld');
    }
  }
  const target = path.join(output,relative);
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,bytes);
  copied.push({ path:relative.replace(/\\/g,'/'), bytes:bytes.length, sha256:crypto.createHash('sha256').update(bytes).digest('hex') });
}
// Never recursively delete arbitrary folders or follow a replaced output symlink.
const deploy = path.dirname(output);
if (fs.existsSync(deploy) && fs.lstatSync(deploy).isSymbolicLink()) throw new Error('Unsafe deploy directory');
if (fs.existsSync(output)) {
  if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(path.join(output,marker))) throw new Error('Existing output is not a generated package');
  if (fs.readdirSync(output).some(name => /^\.env(?:\.|$)/.test(name) && name !== '.env.example')) throw new Error('Refusing to replace a configured deployment');
  if (path.relative(root,output) !== path.join('deploy','cpanel')) throw new Error('Unsafe output path');
  fs.rmSync(output,{recursive:true,force:true});
}
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,marker),'Generated by scripts/build-cpanel.cjs\n');
for (const relative of [...roots,...files]) copy(relative);
// Generate a value-free environment template, independent of developer credentials.
const names = [...new Set(fs.readFileSync(path.join(root,'.env.example'),'utf8').split(/\r?\n/).map(line=>line.match(/^([A-Z][A-Z0-9_]*)=/)?.[1]).filter(Boolean))];
const env = ['# Fill only in cPanel environment settings or a private .env.','NODE_ENV=production','OPEN_BROWSER=0','PORT=3000',...names.filter(n=>!['NODE_ENV','OPEN_BROWSER','PORT'].includes(n)).map(n=>n+'=')];
fs.writeFileSync(path.join(output,'.env.example'),env.join('\n')+'\n');
fs.copyFileSync(path.join(root,'CPANEL.md'),path.join(output,'README.md'));
fs.writeFileSync(path.join(output,'deployment-manifest.json'),JSON.stringify({
  generatedAt:new Date().toISOString(), node:'22.23.4', startup:'new-start.js', adminEnabled:false,
  backend:'Express', database:'Supabase', databaseExportIncluded:false,
  warning:'Local validation only; configure Supabase credentials and verify cPanel before cutover.', files:copied
},null,2)+'\n');
console.log('cPanel + Express + Supabase package created: deploy/cpanel ('+copied.length+' source files).');
