  function cloneLocaleValue(value) {
    if (Array.isArray(value)) {
      return value.map(cloneLocaleValue);
    }
    if (value && typeof value === "object") {
      var copy = {};
      Object.keys(value).forEach(function (key) {
        copy[key] = cloneLocaleValue(value[key]);
      });
      return copy;
    }
    return value;
  }

  function mergeLocale(base, overrides) {
    var result = cloneLocaleValue(base);
    Object.keys(overrides || {}).forEach(function (key) {
      var value = overrides[key];
      if (value && typeof value === "object" && !Array.isArray(value) && result[key] && typeof result[key] === "object" && !Array.isArray(result[key])) {
        result[key] = mergeLocale(result[key], value);
      } else {
        result[key] = cloneLocaleValue(value);
      }
    });
    return result;
  }

  function mergeTeamMemberExtras(language, extras) {
    var locale = site.content.locales[language];
    if (!locale || !locale.team) return;
    Object.keys(extras || {}).forEach(function (memberId) {
      locale.team[memberId] = Object.assign({}, locale.team[memberId], extras[memberId]);
    });
  }

